import { z } from 'zod';
import {
	APPLICATION_SOURCES,
	BILLING_CYCLES,
	CONTRACT_STATUSES,
	type TLicenseApplicationInsert,
	type TLicenseApplicationSelect,
	type TLicenseContractInsert,
	type TLicenseContractSelect,
	type TLicenseKeyInsert,
	type TLicenseKeySelect,
} from '@drizzle/schemas/project.schema';
import type { TTx } from '@drizzle/types';
import type { TPaginationResult } from '@ims-erp/common';

/**
 * Request schemas and the persistence port of the license register (M03
 * stage 1). Business dates are Jakarta `YYYY-MM-DD` strings; money is IDR
 * minor units.
 */

const optionalText = (max: number) =>
	z
		.string()
		.trim()
		.max(max)
		.nullish()
		.transform((value) => (value ? value : null));

export const applicationBodySchema = z.object({
	code: z
		.string()
		.trim()
		.min(1)
		.max(32)
		.regex(/^[A-Za-z0-9._-]+$/, 'Letters, digits, dot, dash and underscore only')
		.transform((value) => value.toUpperCase()),
	name: z.string().trim().min(1).max(200),
	vendor: optionalText(200),
	source: z.enum(APPLICATION_SOURCES),
	description: optionalText(2000),
});

export const contractBodySchema = z.object({
	customerId: z.uuid(),
	licenseApplicationId: z.uuid(),
	packageName: optionalText(200),
	orderId: z.uuid().nullish(),
	startDate: z.iso.date().nullish(),
	endDate: z.iso.date().nullish(),
	billingCycle: z.enum(BILLING_CYCLES),
	contractValue: z.number().int().min(0).max(Number.MAX_SAFE_INTEGER),
	notes: optionalText(4000),
});

export const keyBodySchema = z.object({
	/** Required for third-party applications; generated by the ERP for own ones when empty. */
	licenseKey: optionalText(500),
	maxActivations: z.number().int().min(1).max(100_000).default(1),
	expiresOn: z.iso.date().nullish(),
	notes: optionalText(1000),
});

export const reasonSchema = z.object({ reason: z.string().trim().min(1).max(1000) });

export const contractListQuerySchema = z.object({
	page: z.coerce.number().int().min(1).default(1),
	limit: z.coerce.number().int().min(1).max(100).default(20),
	search: z.string().trim().max(100).optional(),
	status: z.enum(CONTRACT_STATUSES).optional(),
	customerId: z.uuid().optional(),
	/** Only active contracts ending within this many days (ended ones included). */
	dueWithinDays: z.coerce.number().int().min(0).max(366).optional(),
});

export const idParamSchema = z.object({ id: z.uuid() });
export const keyParamSchema = z.object({ id: z.uuid(), keyId: z.uuid() });

export type TApplicationBody = z.output<typeof applicationBodySchema>;
export type TContractBody = z.output<typeof contractBodySchema>;
export type TKeyBody = z.output<typeof keyBodySchema>;
export type TContractListQuery = z.output<typeof contractListQuerySchema>;

/** A contract as listed: with its application. */
export type TContractRow = TLicenseContractSelect & { applicationCode: string; applicationName: string; applicationSource: string };

export type TContractData = Omit<TLicenseContractInsert, 'id' | 'createdAt' | 'updatedAt' | 'deletedAt'>;

/**
 * Persistence port of `licensing.*` (live rows). Status changes are guarded
 * on the current status inside the update (`null` = no longer in that state).
 */
export interface ILicensingRepository {
	listApplications(includeRetired: boolean): Promise<TLicenseApplicationSelect[]>;
	findApplication(id: string): Promise<TLicenseApplicationSelect | null>;
	createApplication(data: Omit<TLicenseApplicationInsert, 'id' | 'createdAt' | 'updatedAt' | 'deletedAt'>): Promise<TLicenseApplicationSelect>;
	updateApplication(id: string, data: Partial<TLicenseApplicationInsert>): Promise<TLicenseApplicationSelect | null>;

	paginateContracts(query: TContractListQuery & { dueBefore?: string }): Promise<TPaginationResult<TContractRow>>;
	findContract(id: string): Promise<TContractRow | null>;
	/** `tx` joins the caller's transaction (number allocation, P7-5). */
	createContract(data: TContractData, tx?: TTx): Promise<TLicenseContractSelect>;
	updateDraft(id: string, data: Partial<TContractData>): Promise<TLicenseContractSelect | null>;
	transition(
		id: string,
		from: TLicenseContractSelect['status'][],
		data: Partial<TLicenseContractInsert>,
		tx?: TTx,
	): Promise<TLicenseContractSelect | null>;
	/** A live draft renewal of this contract, if any. */
	findOpenRenewal(contractId: string): Promise<TLicenseContractSelect | null>;
	/** Active contracts: ending on/after `today` up to `until`, and already ended. */
	countDue(today: string, until: string): Promise<{ endingSoon: number; ended: number }>;
	/**
	 * Draft renewals linked to a sales order and with a start date: the ones
	 * full payment can activate. Narrowed to the renewal of one contract when
	 * `renewedFromContractId` is given.
	 */
	listRenewalCandidates(renewedFromContractId?: string): Promise<TLicenseContractSelect[]>;
	/**
	 * Moves the live keys of a renewed contract to its renewal; a key that
	 * expired with the old contract gets the new end.
	 */
	moveKeys(fromContractId: string, toContractId: string, oldEnd: string | null, newEnd: string | null, tx: TTx): Promise<string[]>;

	listKeys(contractId: string): Promise<TLicenseKeySelect[]>;
	findKeyByValue(licenseKey: string): Promise<TLicenseKeySelect | null>;
	createKey(data: Omit<TLicenseKeyInsert, 'id' | 'createdAt' | 'updatedAt' | 'deletedAt'>): Promise<TLicenseKeySelect>;
	revokeKey(contractId: string, keyId: string, actorUserId: string, reason: string): Promise<TLicenseKeySelect | null>;
}
