/**
 * Licensing domain schema — owns the `licensing` Postgres schema (M03
 * subscription & licensing, stage 1: the register).
 *
 * House rules honoured here:
 * - **Company-wide, no `organization_id`** (ADR-0011/0012), like the
 *   customers the contracts belong to.
 * - Money is bigint IDR minor units (ADR-0002); business dates are Jakarta
 *   `date` strings; operational timestamps are unix ms.
 * - References to other modules (`crm`, `sales`, `auth`) are plain id
 *   columns, validated through those modules' services.
 * - "Expired" and "due" are derived from `end_date`, never stored, so no
 *   background job keeps statuses in step.
 */
import { type AnyPgColumn, bigint, check, date, index, integer, pgSchema, text, uniqueIndex, uuid, varchar } from 'drizzle-orm/pg-core';
import { sql } from 'drizzle-orm';
import { unixTimestamp, unixTimestampNullable } from '@drizzle/datatypes/unix-timestamp';

export const licensingSchema = pgSchema('licensing');

export const APPLICATION_SOURCES = ['third_party', 'own'] as const;
export type ApplicationSource = (typeof APPLICATION_SOURCES)[number];

export const APPLICATION_STATUSES = ['active', 'retired'] as const;
export type ApplicationStatus = (typeof APPLICATION_STATUSES)[number];

export const BILLING_CYCLES = ['monthly', 'quarterly', 'semi_annual', 'annual', 'one_time'] as const;
export type BillingCycle = (typeof BILLING_CYCLES)[number];

/** `draft → active ⇄ suspended → terminated`; `active → renewed` when the renewal activates. */
export const CONTRACT_STATUSES = ['draft', 'active', 'suspended', 'terminated', 'renewed'] as const;
export type ContractStatus = (typeof CONTRACT_STATUSES)[number];

export const KEY_SOURCES = ['vendor', 'generated'] as const;
export type KeySource = (typeof KEY_SOURCES)[number];

export const KEY_STATUSES = ['active', 'revoked'] as const;
export type KeyStatus = (typeof KEY_STATUSES)[number];

const timestamps = {
	createdAt: unixTimestamp('created_at').notNull(),
	updatedAt: unixTimestamp('updated_at')
		.notNull()
		.$onUpdate(() => new Date()),
	deletedAt: unixTimestampNullable('deleted_at'),
};

/* ------------------------------------------------------------------------ *
 * licensing.licensable_applications
 * ------------------------------------------------------------------------ */

export const licensableApplications = licensingSchema.table(
	'licensable_applications',
	{
		id: uuid('id')
			.primaryKey()
			.default(sql`uuidv7()`),
		code: varchar('code', { length: 32 }).notNull(),
		name: text('name').notNull(),
		vendor: text('vendor'),
		/** `third_party`: key typed in from the vendor; `own`: key generated by the ERP. */
		source: text('source').$type<ApplicationSource>().notNull().default('third_party'),
		description: text('description'),
		status: text('status').$type<ApplicationStatus>().notNull().default('active'),
		createdBy: text('created_by'),
		...timestamps,
	},
	(table) => [
		uniqueIndex('licensable_applications_code_uq')
			.on(table.code)
			.where(sql`deleted_at IS NULL`),
		check('licensable_applications_source_check', sql`${table.source} IN ('third_party', 'own')`),
		check('licensable_applications_status_check', sql`${table.status} IN ('active', 'retired')`),
	],
);

/* ------------------------------------------------------------------------ *
 * licensing.license_contracts
 * ------------------------------------------------------------------------ */

export const licenseContracts = licensingSchema.table(
	'license_contracts',
	{
		id: uuid('id')
			.primaryKey()
			.default(sql`uuidv7()`),
		code: varchar('code', { length: 32 }).notNull(),
		/** Logical reference to crm.customers.id. */
		customerId: uuid('customer_id').notNull(),
		customerName: text('customer_name').notNull(),
		licensableApplicationId: uuid('licensable_application_id')
			.notNull()
			.references(() => licensableApplications.id, { onDelete: 'restrict' }),
		packageName: varchar('package_name', { length: 200 }),
		/** Logical reference to sales.sales_orders.id — billing stays in the sales flow. */
		salesOrderId: uuid('sales_order_id'),
		startDate: date('start_date'),
		/** Null = perpetual. */
		endDate: date('end_date'),
		billingCycle: text('billing_cycle').$type<BillingCycle>().notNull().default('annual'),
		contractValue: bigint('contract_value', { mode: 'number' }).notNull().default(0),
		currencyCode: varchar('currency_code', { length: 3 }).notNull().default('IDR'),
		status: text('status').$type<ContractStatus>().notNull().default('draft'),
		renewedFromContractId: uuid('renewed_from_contract_id').references((): AnyPgColumn => licenseContracts.id, {
			onDelete: 'set null',
		}),
		notes: text('notes'),
		createdBy: text('created_by'),
		activatedBy: text('activated_by'),
		activatedAt: unixTimestampNullable('activated_at'),
		terminatedBy: text('terminated_by'),
		terminatedAt: unixTimestampNullable('terminated_at'),
		terminationReason: text('termination_reason'),
		...timestamps,
	},
	(table) => [
		uniqueIndex('license_contracts_code_uq')
			.on(table.code)
			.where(sql`deleted_at IS NULL`),
		index('license_contracts_customer_id_idx').on(table.customerId),
		index('license_contracts_application_id_idx').on(table.licensableApplicationId),
		index('license_contracts_status_idx').on(table.status),
		index('license_contracts_end_date_idx').on(table.endDate),
		check(
			'license_contracts_billing_cycle_check',
			sql`${table.billingCycle} IN ('monthly', 'quarterly', 'semi_annual', 'annual', 'one_time')`,
		),
		check('license_contracts_status_check', sql`${table.status} IN ('draft', 'active', 'suspended', 'terminated', 'renewed')`),
		check('license_contracts_value_check', sql`${table.contractValue} >= 0`),
		check(
			'license_contracts_dates_check',
			sql`${table.endDate} IS NULL OR ${table.startDate} IS NULL OR ${table.endDate} >= ${table.startDate}`,
		),
	],
);

/* ------------------------------------------------------------------------ *
 * licensing.license_keys
 * ------------------------------------------------------------------------ */

export const licenseKeys = licensingSchema.table(
	'license_keys',
	{
		id: uuid('id')
			.primaryKey()
			.default(sql`uuidv7()`),
		licenseContractId: uuid('license_contract_id')
			.notNull()
			.references(() => licenseContracts.id, { onDelete: 'restrict' }),
		/** Readable in stage 1; masked for callers without `license:read_key`. */
		licenseKey: text('license_key').notNull(),
		keySource: text('key_source').$type<KeySource>().notNull().default('vendor'),
		maxActivations: integer('max_activations').notNull().default(1),
		expiresOn: date('expires_on'),
		status: text('status').$type<KeyStatus>().notNull().default('active'),
		notes: text('notes'),
		createdBy: text('created_by'),
		revokedBy: text('revoked_by'),
		revokedAt: unixTimestampNullable('revoked_at'),
		revokeReason: text('revoke_reason'),
		...timestamps,
	},
	(table) => [
		uniqueIndex('license_keys_key_uq')
			.on(table.licenseKey)
			.where(sql`deleted_at IS NULL`),
		index('license_keys_contract_id_idx').on(table.licenseContractId),
		check('license_keys_source_check', sql`${table.keySource} IN ('vendor', 'generated')`),
		check('license_keys_status_check', sql`${table.status} IN ('active', 'revoked')`),
		check('license_keys_max_activations_check', sql`${table.maxActivations} > 0`),
	],
);

export type TLicensableApplicationInsert = typeof licensableApplications.$inferInsert;
export type TLicensableApplicationSelect = typeof licensableApplications.$inferSelect;
export type TLicenseContractInsert = typeof licenseContracts.$inferInsert;
export type TLicenseContractSelect = typeof licenseContracts.$inferSelect;
export type TLicenseKeyInsert = typeof licenseKeys.$inferInsert;
export type TLicenseKeySelect = typeof licenseKeys.$inferSelect;
